create or replace function public.sync_workflow_v3_existing()
returns jsonb language plpgsql security definer set search_path='public','private','pg_temp' as $$
declare v_p integer:=0; v_t integer:=0; r record;
begin
 if private.current_role()<>'CFO' then raise exception 'Only CFO can synchronize Workflow V3'; end if;
 if not private.workflow_v3_enabled() then raise exception 'Workflow V3 is disabled'; end if;
 for r in select id from public.payments loop perform private.ensure_payment_workflow_v3(r.id); v_p:=v_p+1; end loop;
 for r in select id from public.tasks where due_date>=coalesce((select trim(both '"' from setting_value::text)::date from public.finance_settings where setting_key='task_management_v2_go_live_date'),'2026-09-17'::date) loop perform private.ensure_task_workflow_v3(r.id); v_t:=v_t+1; end loop;
 return jsonb_build_object('payments',v_p,'tasks',v_t);
end $$;

grant execute on function public.sync_workflow_v3_existing() to authenticated;

create or replace function public.set_workflow_v3_enabled(p_enabled boolean,p_reason text default null)
returns void language plpgsql security definer set search_path='public','private','pg_temp' as $$
begin
 if private.current_role()<>'CFO' then raise exception 'Only CFO can change Workflow V3 state'; end if;
 insert into public.finance_settings(setting_key,setting_value,updated_by,updated_at) values('workflow_v3_enabled',to_jsonb(p_enabled),auth.uid(),now()) on conflict(setting_key) do update set setting_value=excluded.setting_value,updated_by=excluded.updated_by,updated_at=excluded.updated_at;
 insert into public.audit_log(actor_id,action,entity_type,entity_id,details) values(auth.uid(),'SET_WORKFLOW_V3_STATE','system','workflow_v3',jsonb_build_object('enabled',p_enabled,'reason',nullif(trim(coalesce(p_reason,'')),'')));
end $$;

grant execute on function public.set_workflow_v3_enabled(boolean,text) to authenticated;
