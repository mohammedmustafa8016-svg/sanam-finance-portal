create or replace function public.get_my_work_queue(p_scope text default 'ACTIVE')
returns table(work_item_id uuid,workflow_instance_id uuid,item_type text,source_entity_type text,source_entity_id text,title text,status text,priority text,due_at timestamptz,started_at timestamptz,completed_at timestamptz,assignee_id uuid,assignee_name text,reviewer_id uuid,reviewer_name text,current_step_key text)
language sql stable security definer set search_path='public','private','pg_temp' as $$
 select w.id,w.workflow_instance_id,w.item_type,w.source_entity_type,w.source_entity_id,w.title,w.status,w.priority,w.due_at,w.started_at,w.completed_at,w.assignee_id,a.full_name,w.reviewer_id,r.full_name,i.current_step_key
 from public.work_items w join public.workflow_instances i on i.id=w.workflow_instance_id left join public.profiles a on a.id=w.assignee_id left join public.profiles r on r.id=w.reviewer_id
 where (private.current_role() in ('CFO','Supervisor') or w.assignee_id=auth.uid() or w.reviewer_id=auth.uid())
   and (case upper(coalesce(p_scope,'ACTIVE')) when 'COMPLETED_TODAY' then w.status='Completed' and (w.completed_at at time zone 'Asia/Riyadh')::date=(now() at time zone 'Asia/Riyadh')::date when 'ALL' then true else w.status not in ('Completed','Cancelled') end)
 order by case w.status when 'In Progress' then 1 when 'Ready' then 2 when 'Pending Review' then 3 when 'Blocked' then 4 else 5 end,w.due_at nulls last,w.created_at;
$$;

grant execute on function public.get_my_work_queue(text) to authenticated;

create or replace function public.get_workflow_timeline(p_source_entity_type text,p_source_entity_id text)
returns table(event_time timestamptz,event_type text,actor_name text,title text,details jsonb)
language sql stable security definer set search_path='public','private','pg_temp' as $$
 with wi as(select id from public.workflow_instances where source_entity_type=p_source_entity_type and source_entity_id=p_source_entity_id and private.workflow_can_view_instance(id))
 select e.created_at,e.event_type,p.full_name,w.title,e.details from public.work_item_events e join public.work_items w on w.id=e.work_item_id left join public.profiles p on p.id=e.actor_id where w.workflow_instance_id in(select id from wi)
 order by e.created_at;
$$;

grant execute on function public.get_workflow_timeline(text,text) to authenticated;

create or replace function public.get_workflow_v3_performance(p_date_from date default null,p_date_to date default null)
returns table(user_id uuid,full_name text,role text,completed_items integer,manual_tasks integer,transaction_items integer,on_time_items integer,late_items integer,on_time_rate numeric,total_units numeric)
language sql stable security definer set search_path='public','private','pg_temp' as $$
 with ctx as(select coalesce(p_date_from,(now() at time zone 'Asia/Riyadh')::date) d1,coalesce(p_date_to,(now() at time zone 'Asia/Riyadh')::date) d2,private.current_role() role,auth.uid() uid),
 people as(select p.* from public.profiles p,ctx c where p.active=true and (c.role in ('CFO','Supervisor') or p.id=c.uid)),
 x as(select pe.id,count(w.id) filter(where w.status='Completed')::int completed,count(w.id) filter(where w.status='Completed' and w.source_entity_type='task')::int manual,count(w.id) filter(where w.status='Completed' and w.source_entity_type<>'task')::int txn,count(w.id) filter(where w.status='Completed' and (w.due_at is null or w.completed_at<=w.due_at))::int ontime,count(w.id) filter(where w.status='Completed' and w.due_at is not null and w.completed_at>w.due_at)::int late,coalesce(sum(w.performance_units) filter(where w.status='Completed'),0) units from people pe cross join ctx c left join public.work_items w on w.completed_by=pe.id and (w.completed_at at time zone 'Asia/Riyadh')::date between c.d1 and c.d2 group by pe.id)
 select pe.id,pe.full_name,pe.role,x.completed,x.manual,x.txn,x.ontime,x.late,case when x.completed=0 then 0 else round(x.ontime*100.0/x.completed,1) end,x.units from people pe join x on x.id=pe.id order by pe.role,pe.full_name;
$$;

